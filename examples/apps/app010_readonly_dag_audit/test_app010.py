"""APP-010: genuinely read-only DAG audit of actual APP-009 native executions.

All original fixtures are generated by compiled Rust NORDOI invoked through
APP-009, not invented positive receipts. Mutations are adversarial descendants.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SOURCE = REPO / "examples/apps/app003_integrated_quality/src"
NATIVE = Path(os.environ.get("NORDOI_APP010_EXE", str(
    REPO / "target/debug" / ("nordoi.exe" if os.name == "nt" else "nordoi")
)))
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "app009_agent_dag"))
import audit_app010 as independent
import run_app009 as producer


def node(value: int, deps=None, gate: str = "always") -> dict:
    return {"key_code": value, "depends_on": [] if deps is None else deps,
            "gate": gate}


class ReadOnlyAgentDagAudit(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="nordoi_app010_real_")
        self.base = Path(self.tmp.name)
        self.root = self.base / "real-published-jobs"
        self.root.mkdir()
        self.plan = self.base / "native-plan.json"
        self.events = self.base / "real-native-events.jsonl"
        self.source = SOURCE
        self.engine = NATIVE
        self.generate([node(73), node(59), node(60, [1, 2], "all_committed")])

    def tearDown(self):
        self.tmp.cleanup()

    def generate(self, nodes):
        shutil.rmtree(self.root)
        self.root.mkdir()
        self.plan.write_text(json.dumps({"schema": producer.SCHEMA,
            "nodes": nodes}, ensure_ascii=True,
            separators=(",", ":")), encoding="utf-8")
        self.plan_pin = hashlib.sha256(self.plan.read_bytes()).hexdigest()
        cmd = [sys.executable, "-B", str(HERE.parent / "app009_agent_dag/run_app009.py"),
               "--plan", str(self.plan), "--engine", str(self.engine),
               "--source-root", str(self.source),
               "--grant-output-dir", str(self.root),
               "--expected-engine-sha256", producer.pinned.engine_sha256(self.engine),
               "--expected-source-sha256", producer.pinned.source_tree_sha256(self.source)]
        self.native_proc = subprocess.run(cmd, capture_output=True,
                                          cwd=REPO, timeout=145)
        self.events.write_bytes(self.native_proc.stdout)

    def check(self):
        proc = subprocess.run(
            [sys.executable, "-B", str(HERE / "audit_app010.py"),
             "--dag-root", str(self.root), "--plan", str(self.plan),
             "--events", str(self.events),
             "--expected-plan-sha256", self.plan_pin],
            capture_output=True, cwd=REPO, timeout=30,
        )
        try:
            report = json.loads(proc.stdout.decode("utf-8", "strict"))
        except (UnicodeError, json.JSONDecodeError):
            self.fail(f"audit emitted non-json: {proc.stdout!r}, {proc.stderr!r}")
        return proc, report

    def accepted(self, status="PASS", n=3):
        proc, record = self.check()
        self.assertEqual(proc.returncode, 0, (record, proc.stderr))
        self.assertEqual(record["status"], status)
        self.assertEqual(record["committed_jobs_verified"], n)
        return record

    def denied(self, code):
        proc, record = self.check()
        self.assertEqual(proc.returncode, 2, (record, proc.stderr))
        self.assertEqual(record["status"], "REJECTED")
        self.assertEqual(record["error_code"], code)
        self.assertIs(record["verified"], False)

    def mutate(self, update):
        rows = [json.loads(x) for x in self.events.read_text(encoding="utf-8").splitlines()]
        update(rows)
        self.events.write_text("".join(json.dumps(
            row, separators=(",", ":"), ensure_ascii=True)+"\n" for row in rows),
            encoding="utf-8")

    def test_01_true_three_job_native_join_is_audited(self):
        self.assertEqual(self.native_proc.returncode, 0, self.native_proc.stderr)
        r = self.accepted()
        self.assertEqual(r["events_checked"], 3)
        self.assertEqual(r["skipped_nodes_verified"], 0)

    def test_02_exact_native_files_are_observed_not_engine_reexecuted(self):
        r = self.accepted()
        self.assertEqual(len(r["verified_jobs"]), 3)
        self.assertTrue(all(len(x["files"]) == 2 for x in r["verified_jobs"]))

    def test_03_original_plan_and_event_digest_match_real_data(self):
        r = self.accepted()
        self.assertEqual(r["plan_sha256"],
                         hashlib.sha256(self.plan.read_bytes()).hexdigest())
        self.assertEqual(r["original_events_sha256"],
                         hashlib.sha256(self.events.read_bytes()).hexdigest())
        # Test the authentic Windows CRLF transport on all four operating systems.
        # The auditor must preserve exact raw bytes for its SHA-256 report.
        normalized = self.events.read_bytes().replace(b"\r\n", b"\n")
        self.events.write_bytes(normalized.replace(b"\n", b"\r\n"))
        again = self.accepted()
        self.assertEqual(again["original_events_sha256"],
                         hashlib.sha256(self.events.read_bytes()).hexdigest())

    def test_04_audit_is_byte_deterministic(self):
        first, a = self.check()
        second, b = self.check()
        self.assertEqual(first.stdout, second.stdout)
        self.assertEqual(a, b)

    def test_05_audit_does_not_write_to_original_native_files(self):
        watched = [self.plan, self.events,
                   self.root/"job-0001/quality-decision/decision.txt",
                   self.root/"job-0003/quality-decision/report.txt"]
        original = [p.read_bytes() for p in watched]
        self.accepted()
        self.assertEqual(original, [p.read_bytes() for p in watched])

    def test_06_one_real_job_is_audited(self):
        self.generate([node(73)])
        self.accepted(n=1)

    def test_07_eight_real_jobs_audited_with_bounds(self):
        self.generate([node(x) for x in (0, 20, 59, 60, 61, 73, 90, 100)])
        self.accepted(n=8)

    def test_08_approved_and_rejected_joins_are_recomputed(self):
        self.generate([node(73), node(80), node(59, [1, 2], "all_approved")])
        self.accepted()
        self.generate([node(59), node(0), node(73, [1, 2], "all_rejected")])
        self.accepted()

    def test_09_any_approved_real_join_is_recomputed(self):
        self.generate([node(59), node(73), node(60, [1, 2], "any_approved")])
        self.accepted()

    def test_10_any_rejected_real_join_is_recomputed(self):
        self.generate([node(73), node(59), node(60, [1, 2], "any_rejected")])
        self.accepted()

    def test_11_real_skipped_node_is_verified_without_file(self):
        self.generate([node(59), node(73, [1], "all_approved")])
        r = self.accepted(n=1)
        self.assertEqual(r["skipped_nodes_verified"], 1)
        self.assertFalse((self.root/"job-0002").exists())

    def test_12_skipped_dependency_is_not_a_committed_parent(self):
        self.generate([node(59), node(73, [1], "all_approved"),
                       node(60, [2], "all_committed")])
        r = self.accepted(n=1)
        self.assertEqual(r["skipped_nodes_verified"], 2)

    def test_13_any_approved_from_other_parent_accepts_true_join(self):
        self.generate([node(59), node(73, [1], "all_approved"), node(73),
                       node(60, [2, 3], "any_approved")])
        r = self.accepted(n=3)
        self.assertEqual(r["skipped_nodes_verified"], 1)

    def test_14_real_original_native_failure_is_never_pass(self):
        self.source = self.base/"mutated-source"
        shutil.copytree(SOURCE, self.source)
        rule = self.source/"app/rules.noi"
        old = rule.read_text(encoding="utf-8")
        self.assertIn("else { 0 }", old)
        rule.write_text(old.replace("else { 0 }", "else { 2 }"),
                        encoding="utf-8")
        self.generate([node(73), node(59), node(60)])
        self.assertNotEqual(self.native_proc.returncode, 0)
        p, r = self.check()
        self.assertEqual(p.returncode, 3, (r, p.stderr))
        self.assertEqual(r["status"], "INCONCLUSIVE")
        self.assertEqual(r["committed_jobs_verified"], 1)
        self.assertEqual(r["terminal_error"], "NATIVE_OPERATION_FAILED")

    def test_15_truncated_event_stream_is_never_full_pass(self):
        self.mutate(lambda rows: rows.pop())
        shutil.rmtree(self.root/"job-0003")
        p, r = self.check()
        self.assertEqual(p.returncode, 3, (r, p.stderr))
        self.assertEqual(r["status"], "INCONCLUSIVE")
        self.assertEqual(r["committed_jobs_verified"], 2)

    def test_16_one_native_file_changed_is_rejected(self):
        target = self.root/"job-0002/quality-decision/report.txt"
        target.write_bytes(target.read_bytes() + b"forged")
        self.denied("REAL_FILE_CONTENT_DIFFERS_FROM_RECEIPT")

    def test_17_one_original_native_file_deleted_is_rejected(self):
        (self.root/"job-0002/quality-decision/report.txt").unlink()
        self.denied("BUNDLE_FILE_SET_CHANGED")

    def test_18_extra_file_inside_real_bundle_is_rejected(self):
        (self.root/"job-0001/quality-decision/extra.txt").write_text("untrusted")
        self.denied("BUNDLE_FILE_SET_CHANGED")

    def test_19_extra_job_directory_is_rejected(self):
        (self.root/"job-0004").mkdir()
        self.denied("ROOT_UNEXPECTED_JOB_OR_FILE")

    def test_20_forged_skip_on_genuine_committed_gate_is_rejected(self):
        def tamper(rows):
            rows[2] = {"schema": producer.EVENT, "step": 3, "status": "SKIPPED",
                       "gate": "all_committed", "depends_on": [1, 2],
                       "plan_sha256": self.plan_pin, "reason": "DEPENDENCY_GATE_FALSE"}
        self.mutate(tamper)
        self.denied("UNJUSTIFIED_SKIPPED_NODE")

    def test_21_forged_commit_on_a_false_gate_is_rejected(self):
        self.generate([node(59), node(73, [1], "all_approved")])
        source_row = json.loads(self.events.read_text().splitlines()[0])
        def tamper(rows):
            rows[1] = dict(source_row, step=2, job="job-0002",
                           gate="all_approved", depends_on=[1])
        self.mutate(tamper)
        self.denied("EXECUTED_NODE_WHEN_GATE_FALSE")

    def test_22_forged_native_decision_number_is_rejected(self):
        self.mutate(lambda rows: rows[0].__setitem__("decision", 0))
        self.denied("NATIVE_DECISION_CONTRADICTION")

    def test_23_forged_native_key_code_is_rejected(self):
        self.mutate(lambda rows: rows[0]["native_receipt"].__setitem__("key_code", 72))
        self.denied("NATIVE_KEY_CODE_MISMATCH")

    def test_24_wrong_job_identity_is_rejected(self):
        self.mutate(lambda rows: rows[1].__setitem__("job", "job-0001"))
        self.denied("JOB_ID_NOT_BOUND_TO_DAG_STEP")

    def test_25_forged_edge_list_is_rejected(self):
        self.mutate(lambda rows: rows[2].__setitem__("depends_on", [2]))
        self.denied("EVENT_DAG_BINDING_MISMATCH")

    def test_26_forged_gate_is_rejected(self):
        self.mutate(lambda rows: rows[2].__setitem__("gate", "any_approved"))
        self.denied("EVENT_DAG_BINDING_MISMATCH")

    def test_27_event_plan_digest_mismatch_is_rejected(self):
        self.mutate(lambda rows: rows[0].__setitem__("plan_sha256", "a"*64))
        self.denied("EVENT_PLAN_DIGEST_MISMATCH")

    def test_28_caller_supplied_plan_pin_mismatch_is_rejected(self):
        self.plan_pin = "0"*64
        self.denied("PLAN_SHA256_PIN_MISMATCH")

    def test_29_plan_changed_without_pin_change_is_rejected(self):
        data = json.loads(self.plan.read_text(encoding="utf-8"))
        data["nodes"][0]["key_code"] = 70
        self.plan.write_text(json.dumps(data), encoding="utf-8")
        self.denied("PLAN_SHA256_PIN_MISMATCH")

    def test_30_unknown_event_field_is_rejected(self):
        self.mutate(lambda rows: rows[0].__setitem__("grant", "/tmp"))
        self.denied("COMMITTED_FIELDS_INVALID")

    def test_31_duplicate_raw_json_event_field_is_rejected(self):
        raw = self.events.read_bytes()
        self.events.write_bytes(raw.replace(b'"status":"COMMITTED"',
                                      b'"status":"COMMITTED","status":"COMMITTED"', 1))
        self.denied("DUPLICATE_RECEIPT_FIELD")

    def test_32_invalid_event_utf8_is_rejected(self):
        self.events.write_bytes(b"\xff\n")
        self.denied("EVENT_INVALID_JSON")

    def test_33_invalid_event_json_is_rejected(self):
        self.events.write_bytes(b"{not-json}\n")
        self.denied("EVENT_INVALID_JSON")

    def test_34_event_missing_final_newline_is_rejected(self):
        self.events.write_bytes(self.events.read_bytes().rstrip(b"\n"))
        self.denied("EVENTS_NOT_NEWLINE_TERMINATED")

    def test_35_reordered_native_events_are_rejected(self):
        def swap(rows):
            rows[0], rows[1] = rows[1], rows[0]
        self.mutate(swap)
        self.denied("EVENT_SCHEMA_OR_STEP_INVALID")

    def test_36_duplicate_event_after_all_nodes_is_rejected(self):
        self.mutate(lambda rows: rows.append(dict(rows[-1])))
        self.denied("EVENT_COUNT_EXCEEDS_PLAN")

    def test_37_root_symlink_is_rejected_when_supported(self):
        link = self.base/"fake-root"
        try:
            link.symlink_to(self.root, target_is_directory=True)
        except (OSError, NotImplementedError):
            self.skipTest("OS forbids symlink")
        old = self.root
        self.root = link
        self.denied("BATCH_ROOT_NOT_REAL_DIRECTORY")
        self.root = old

    def test_38_native_file_symlink_is_rejected_when_supported(self):
        target = self.root/"job-0001/quality-decision/report.txt"
        genuine = target.read_bytes()
        target.unlink()
        outside = self.base/"outside-report.txt"
        outside.write_bytes(genuine)
        try:
            target.symlink_to(outside)
        except (OSError, NotImplementedError):
            self.skipTest("OS forbids symlink")
        self.denied("FILE_MISSING_SYMLINK_OR_OVERSIZED")

    def test_39_empty_events_are_rejected(self):
        self.events.write_bytes(b"")
        self.denied("EVENTS_NOT_NEWLINE_TERMINATED")

    def test_40_unverified_native_proof_is_not_misrepresented(self):
        r = self.accepted()
        self.assertEqual(r["attestation"],
                         "READ_ONLY_DAG_AND_REAL_FILE_CONSISTENCY_NOT_SIGNED")
        self.assertEqual(r["p27_native_proof"],
                         "SHAPE_ONLY_NOT_CRYPTOGRAPHICALLY_RECOMPUTED")
        self.assertEqual(r["external_pin_authentication"], "NOT_PERFORMED")
        self.assertEqual(r["crash_durability"], "UNCLAIMED")


